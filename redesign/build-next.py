#!/usr/bin/env python3
"""Make next.html (Redesign v2 sample) from index.html.

index.html is never changed. next.html = index.html + three injected lines:
  1. extra fonts for Japanese / Chinese,
  2. redesign/v2.css after the app's styles,
  3. redesign/v2.js after the app's script.
Run after every change to index.html:  python3 redesign/build-next.py
"""
from pathlib import Path
root = Path(__file__).resolve().parent.parent
s = (root / "index.html").read_text(encoding="utf-8")
FONTS = '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Noto+Sans+JP:wght@400;700&family=Noto+Sans+SC:wght@400;700&family=Noto+Sans+TC:wght@400;700&display=swap">'
def once(text, old, new):
    assert text.count(old) == 1, f"marker not found exactly once: {old[:40]}"
    return text.replace(old, new)
s = once(s, "</head>", f"{FONTS}\n<link rel=\"stylesheet\" href=\"redesign/v2.css\">\n</head>")
i = s.rfind("</body>")
assert i > 0
s = s[:i] + '<script src="redesign/v2.js"></script>\n' + s[i:]
s = s.replace("<title>", "<title>[v2] ", 1)
s = once(s, "<html", "<!-- GENERATED by redesign/build-next.py from index.html. Do not edit; edit redesign/v2.css / v2.js instead. -->\n<html")
(root / "next.html").write_text(s, encoding="utf-8")
print("next.html written")
