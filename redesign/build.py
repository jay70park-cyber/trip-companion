#!/usr/bin/env python3
"""Make the dated test page (e.g. 1120.html) of the redesign from index.html.

Usage:  python3 redesign/build.py          -> MMDD.html for today (Korea time)
        python3 redesign/build.py 1120     -> 1120.html
index.html is never changed. The test page = index.html + three injected lines:
  1. extra fonts for Japanese / Chinese,
  2. redesign/v2.css after the app's styles,
  3. redesign/v2.js after the app's script.
Run again after every change to index.html (same date name overwrites that day's page).
"""
import sys, datetime
from pathlib import Path
root = Path(__file__).resolve().parent.parent
s = (root / "index.html").read_text(encoding="utf-8")
FONTS = '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Noto+Sans+JP:wght@400;700&family=Noto+Sans+SC:wght@400;700&family=Noto+Sans+TC:wght@400;700&display=swap">'
def once(text, old, new):
    assert text.count(old) == 1, f"marker not found exactly once: {old[:40]}"
    return text.replace(old, new)
name = sys.argv[1] if len(sys.argv) > 1 else (datetime.datetime.utcnow() + datetime.timedelta(hours=9)).strftime("%m%d")
assert name.isdigit() and len(name) == 4, "use a date like 1120"
# freeze this day's overlay so earlier date pages keep showing what they showed
snap = root / "redesign" / "snap" / name
snap.mkdir(parents=True, exist_ok=True)
for f in ("v2.css", "v2.js"):
    (snap / f).write_text((root / "redesign" / f).read_text(encoding="utf-8"), encoding="utf-8")
s = once(s, "</head>", f"{FONTS}\n<link rel=\"stylesheet\" href=\"redesign/snap/{name}/v2.css\">\n</head>")
i = s.rfind("</body>")
assert i > 0
s = s[:i] + f'<script src="redesign/snap/{name}/v2.js"></script>\n' + s[i:]
s = s.replace("<title>", "<title>[test] ", 1)
s = once(s, "<html", "<!-- GENERATED by redesign/build.py from index.html. Do not edit; edit redesign/v2.css / v2.js instead. -->\n<html")
(root / f"{name}.html").write_text(s, encoding="utf-8")
print(f"{name}.html written")
